import assert from 'node:assert/strict';
import console from 'node:console';
import process from 'node:process';
import { randomUUID } from 'node:crypto';
import { generateBlueprintV2, normalizeBlueprintV2Requirements } from '@designflow/generator';
import { auditBlueprint } from '@designflow/blueprint-qa';
import { calculateQuantityTakeoff } from '@designflow/quantity-takeoff';
import { initialConversation, planConversation } from './apps/api/dist/ai/conversation-planner.js';
import { solverV2QaOptions } from './apps/api/dist/services/solver-v2-qa.js';
import { requirementsHash, modelHash } from './apps/api/dist/lib/generation-identity.js';
const requirements=normalizeBlueprintV2Requirements({site:{boundary:[{x:0,z:0},{x:12000,z:0},{x:12000,z:16000},{x:0,z:16000}],northMilliDegrees:0},rooms:[{type:'bedroom',count:2},{type:'living',count:1},{type:'kitchen',count:1},{type:'bathroom',count:1}],seed:'stabilization-container',layoutV2:{accessSide:'min-z',parking:{count:1}},solver:{maxCandidates:8}});
const message=(text,extra={})=>({messageId:randomUUID(),expectedVersion:0,baseRevisionId:null,text,...extra});
let state=initialConversation(null,requirements,true);
state=await planConversation(state,message('Make the kitchen bigger'));
assert.equal(state.status,'NEEDS_CLARIFICATION');
state=await planConversation(state,message('Use these values',{answers:[{field:'kitchen.minimumDimensions',value:{widthMm:2200,depthMm:2300}}]}));
assert.equal(state.status,'AWAITING_APPROVAL');
assert.deepEqual(state.requirements.site,requirements.site);assert.deepEqual(state.requirements.layoutV2,requirements.layoutV2);
assert.equal(state.proposal.requirementsHash,requirementsHash(state.requirements));
const generated=generateBlueprintV2(state.proposal.requirements);
const qa=auditBlueprint(generated.model,{requireReachability:true,...solverV2QaOptions(state.requirements)});
assert.notEqual(qa.status,'FAIL');
const coverage=calculateQuantityTakeoff(generated.model).coverage.find(c=>c.category==='parking_construction');
assert.equal(coverage.status,'NOT_EVALUATED');
let ambiguous=await planConversation(initialConversation(null,null,false),message('30 by 50 feet 3BHK two floors'));
ambiguous=await planConversation(ambiguous,message('Move one bedroom upstairs'));
ambiguous=await planConversation(ambiguous,message('seed unchanged'));
assert.equal(ambiguous.proposal,null);assert.equal(ambiguous.pendingBedroomMove,true);
console.log(JSON.stringify({runtime:'compiled production container; network none',solver:generated.metadata.solverVersion,qa:qa.status,modelHash:modelHash(generated.model),requirementsHash:state.proposal.requirementsHash,parkingCoverage:coverage.status,conversationStatus:state.status,ambiguousMoveStatus:ambiguous.status,nonRoot:process.getuid()!==0}));
